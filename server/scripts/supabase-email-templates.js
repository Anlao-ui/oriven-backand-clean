// Writes the Supabase Auth email templates (services/email/templates.js →
// supabaseAuthTemplate) to docs/email/, ready to paste into
// Supabase → Authentication → Emails. Run after changing the template:
//   node scripts/supabase-email-templates.js          write the files
//   node scripts/supabase-email-templates.js --check  exit 1 if they are stale
// No network, no credentials: Supabase sends these, not this server.
const fs = require('fs');
const path = require('path');
const T = require('../services/email/templates');

const OUT = path.join(__dirname, '..', 'docs', 'email');
const FILES = { reset_password: 'supabase-reset-password.html' };

let stale = false;
for (const [kind, file] of Object.entries(FILES)) {
  const t = T.supabaseAuthTemplate(kind);
  const html = `<!-- Supabase → Authentication → Emails → "Reset password". Subject: ${t.subject}\n` +
    `     Generated by scripts/supabase-email-templates.js from services/email/templates.js — edit the source, not this file. -->\n` + t.html + '\n';
  const target = path.join(OUT, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (process.argv.includes('--check')) { if (current !== html) { stale = true; console.log('stale: docs/email/' + file); } continue; }
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(target, html);
  console.log('wrote docs/email/' + file + ' (subject: ' + t.subject + ')');
}
if (stale) process.exit(1);
